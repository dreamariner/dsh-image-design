// 素体姿势库：每姿势 = 全关节欧拉表（弧度）。
//
// 骨架是自建的（局部旋转全是单位阵 → 骨的朝向就是世界朝向），所以姿势欧拉按
// **父骨相对轴**书写（级联）：骨的最终朝向 = 父骨新朝向 ∘ 自身欧拉。
// 因此每个数值都是「相对上一节的屈曲量」，不是绝对世界角。
//
// ── 关节正负号（2026-11-17 用真 three.js 骨架逐项标定）──
//   · 髋 hip       x < 0 = 大腿前屈（膝往前上方走）；x > 0 = 后伸（腿往后摆）
//   · 膝 knee      x > 0 = 小腿向后折（屈膝）。**x < 0 是反关节，任何姿势都不允许**。
//                  x=1.5(86°) 小腿水平向后；x=2.5(143°) 小腿折到后上方。
//   · 踝 ankle     x > 0 = 跖屈（脚尖下压）；x < 0 = 背屈（脚尖上抬）。
//                  ← 这一项此前注释写反了，导致跪坐脚背朝前翘，是全表最严重的一处错。
//   · 肩 shoulder  x < 0 = 手臂前摆；x > 0 = 后摆；z > 0 = 外展抬起（左臂），
//                  右臂镜像取负。A-pose 本身已外展约 40°，所以 z=0 不是「贴体侧」。
//   · 肘 elbow     x < 0 = 屈肘（前臂向前/上折）；x > 0 = 过伸。
//                  **过伸超过 5° 即反关节**，参考图里的肘会朝后凸出，一眼就假。
//   · 脊柱 spine/chest  x > 0 = 前倾。
//
// 绑定姿态就是 A-pose（手臂外展 43° + 前倾 23°），所以 a-pose = 全零表；
// 「手臂自然下垂」是另一个姿势 stand，它要把这两个偏移都补偿掉。
//
// **骨盆高度不写进姿势表**：姿势应用后由 viewer 按蒙皮后的真实最低点自动落地
// （viewer.ts 的 reground）。坐/跪的髋高由关节角自然决定，写死会与体型冲突。
//
// 每姿势存**全关节表**（缺省关节 = 零旋转）：拍参考图时整表钉进 ref.json，
// 姿势库后续增删改不影响旧参考图的可复现性。
//
// ── 数值来源 ──
// 没有动作捕捉数据。每个姿势是在真骨架 + 真蒙皮上做参数搜索得到的：先定「手/膝/踝/
// 臀应落在哪」的解剖约束，再扫关节角网格取几何残差最小的一组。判据固化在
// tests/pose-geometry.spec.ts，改姿势会立刻被断言拦住（例如肘过伸、脚尖朝前）。

import { JOINT_NAMES, type JointName } from './body.ts'

export interface JointRotations {
  [joint: string]: { x: number; y: number; z: number }
}

export interface PoseDef {
  id: string
  title: string
  joints: JointRotations
}

const zero = (): JointRotations => {
  const t: JointRotations = {}
  for (const j of JOINT_NAMES) t[j] = { x: 0, y: 0, z: 0 }
  return t
}

/** 补全姿势表：缺省关节补零，多余关节剔除（存档前调用）。 */
export function normalizePose(partial: JointRotations): JointRotations {
  const t = zero()
  for (const j of JOINT_NAMES) {
    const v = partial[j]
    if (v !== undefined) t[j] = { x: v.x, y: v.y, z: v.z }
  }
  return t
}

/** 取姿势的规范化全关节表（姿势存在取库值；否则按 unknown 处理零表）。 */
export function poseJoints(id: string): JointRotations {
  const pose = POSES.find((p) => p.id === id)
  return pose !== undefined ? normalizePose(pose.joints) : zero()
}

