// 绑定姿态的手臂相对肩关节**外展 43° + 前倾 23°**：shoulder=0 时手已经在肩外侧 26cm、
// 前方 18cm，是「斜着往前伸」，既不在体侧也不在身前。
//
// 因此「手垂在体侧」要同时补偿两个轴：
//   · x（矢状面）后摆 0.46 → 抵消前倾 23°
//   · z（冠状面）内收 0.65 → 抵消外展 43°（左臂取负、右臂取正）
// 只补前倾（第二轮的做法）会让 a-pose/stand/walk 从正面看像稻草人：手腕停在体侧 43cm，
// 而 1.69m 的人自然下垂时手腕应在 21cm 左右（髂嵴外侧一点）。这是第三轮补的根因。
const ARM_SWING = 0.46
const ARM_ADDUCT = 0.65

/** 左肩：swing>0 = 后摆，adduct>0 = 再往里收，twist = 水平面内的前后微偏。 */
const armL = (swing = 0, adduct = 0, twist = 0) => ({
  x: ARM_SWING + swing, y: twist, z: -(ARM_ADDUCT + adduct),
})
/** 右肩：与左肩严格镜像（x 相同、y/z 取反）。 */
const armR = (swing = 0, adduct = 0, twist = 0) => ({
  x: ARM_SWING + swing, y: -twist, z: ARM_ADDUCT + adduct,
})

